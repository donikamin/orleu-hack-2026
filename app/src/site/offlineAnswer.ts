/** Простое вычисление: «сколько будет 25*4», «12,5 + 7». Только цифры и знаки — без выполнения кода. */
function arithmetic(q: string): string | null {
  const m = /(?:сколько будет|посчитай|вычисли|реши)?\s*([-\d\s.,+*/×x÷:()]+)\s*(?:=|\?)?\s*$/i.exec(q.replace(/плюс/g, '+').replace(/минус/g, '-').replace(/умножить на/g, '*').replace(/разделить на/g, '/'));
  if (!m || !/\d\s*[-+*/×x÷:]\s*\d/.test(m[1])) return null;
  const expr = m[1].replace(/\s/g, '').replace(/,/g, '.').replace(/[×x]/g, '*').replace(/[÷:]/g, '/');
  if (!/^[-\d.+*/()]+$/.test(expr)) return null;
  // разбор выражения: числа, + - * / и скобки
  let i = 0;
  const num = (): number => {
    if (expr[i] === '(') {
      i++;
      const v = sum();
      i++;
      return v;
    }
    if (expr[i] === '-') {
      i++;
      return -num();
    }
    const s = /^\d+(\.\d+)?/.exec(expr.slice(i));
    if (!s) throw new Error('bad');
    i += s[0].length;
    return Number(s[0]);
  };
  const prod = (): number => {
    let v = num();
    while (expr[i] === '*' || expr[i] === '/') {
      const op = expr[i++];
      const r = num();
      v = op === '*' ? v * r : v / r;
    }
    return v;
  };
  const sum = (): number => {
    let v = prod();
    while (expr[i] === '+' || expr[i] === '-') {
      const op = expr[i++];
      const r = prod();
      v = op === '+' ? v + r : v - r;
    }
    return v;
  };
  try {
    const v = sum();
    if (i !== expr.length || !Number.isFinite(v)) return null;
    const pretty = Math.round(v * 1000) / 1000;
    return `${m[1].trim()} = ${pretty.toLocaleString('ru-RU')}. Проверь себя: попробуй прикинуть ответ в уме перед тем, как считать.`;
  } catch {
    return null;
  }
}

