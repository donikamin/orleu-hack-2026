function sentences(text: string) {
  return text.replace(/\n+/g, ' ').match(/[^.!?…]+[.!?…]+/g)?.map((s) => s.trim()) ?? [text];
}

function aboutText(q: string, ctx: { title: string; body: string }): string | null {
  const paras = ctx.body.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
  const all = sentences(ctx.body);
  if (/о ч[её]м|кратко|в двух словах|пересказ|суть/i.test(q)) {
    const firsts = paras.slice(0, 3).map((p) => sentences(p)[0]);
    return `Текст «${ctx.title}» вот о чём. ${firsts.join(' ')} Попробуй теперь сказать это одной фразой своими словами.`;
  }
  if (/главн|основн|мысл|идея|вывод/i.test(q)) {
    const last = sentences(paras[paras.length - 1] ?? ctx.body);
    return `Главную мысль часто пишут в начале или в конце. В этом тексте смотри на последний абзац: «${last[last.length - 1]}» Согласен, что это главное? Почему?`;
  }
  if (/слов|значит|термин|непонятн/i.test(q)) {
    const words = ctx.body.match(/[А-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі-]{9,}/g) ?? [];
    const word = words.sort((a, b) => b.length - a.length)[0];
    if (!word) return null;
    const where = all.find((s) => s.includes(word)) ?? '';
    return `Возьмём слово «${word.toLowerCase()}». Оно стоит в предложении: «${where}» Попробуй понять его по смыслу соседних слов. Если не выходит, найди в слове знакомую часть — корень часто подсказывает значение.`;
  }
  return null;
}

/* ---------- Разговор: приветствия, «как дела», «кто ты» и т. п. Несколько вариантов, без повторов подряд ---------- */
const lastPick = new Map<string, number>();
function pick(key: string, variants: string[]) {
  let i = Math.floor(Math.random() * variants.length);
  if (variants.length > 1 && i === lastPick.get(key)) i = (i + 1) % variants.length;
  lastPick.set(key, i);
  return variants[i];
}

