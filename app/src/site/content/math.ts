export function checkMath(t: MathTask, raw: string): boolean {
  const v = Number(raw.replace(/\s/g, '').replace(',', '.'));
  if (!Number.isFinite(v)) return false;
  return Math.abs(v - t.answer) <= (t.tolerance ?? 0.001);
}
