// Задания новых форматов — не только выбор варианта.
//  cite  — «Докажи цитатой»: нажми предложение текста, которое доказывает ответ (навык PISA «найти» + «понять»).
//  tf    — «Верно / неверно»: несколько утверждений про таблицу, график или текст.
//  order — «Собери решение»: расставь шаги решения задачи по порядку.
//  point — «Нажми на график»: найди точку на графике.
import type { Chart } from './lessons';

interface Base {
  id: string;
  subject: 'reading' | 'math';
  title: string;
  difficulty: 1 | 2 | 3;
  question: string;
  hints: [string, string, string];
  explanation: string;
}
export type MixTask = Base &
  (
    | { kind: 'cite'; sentences: string[]; correct: number[] }
    | { kind: 'tf'; context: string; chart?: Chart; table?: { head: string[]; rows: (string | number)[][] }; statements: { text: string; ok: boolean }[] }
    | { kind: 'order'; context: string; steps: string[] } // steps в правильном порядке, на экране перемешаны
    | { kind: 'point'; context: string; chart: Chart; correct: string }
  );

